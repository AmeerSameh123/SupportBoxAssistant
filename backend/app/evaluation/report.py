"""Renders eval/report.md — the EVIDENCE for the error analysis, not the analysis.

The split is deliberate (PRD §11.7). This module produces the confusion matrix and
the per-ticket disagreement table. `eval/ERROR_ANALYSIS.md` is written by hand,
because generated prose is exactly what falls apart when someone asks "why did it
fail here?" in an interview. The script produces evidence; I produce the argument.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

from app.evaluation.metrics import (
    CATEGORY_LABELS,
    PRIORITY_LABELS,
    CalibrationReport,
    Score,
    cohens_kappa,
    confusion_matrix,
    macro_f1,
    per_class_metrics,
)


def render_report(
    *,
    category_pairs: list[tuple[str, str]],
    priority_pairs: list[tuple[str, str]],
    category_score: Score,
    priority_score: Score,
    priority_within_one: Score,
    majority: Score,
    heuristic_score: Score,
    calibration_raw: CalibrationReport,
    calibration_calibrated: CalibrationReport,
    disagreements: Sequence[dict[str, Any]],
    health: dict[str, Any],
    run_metadata: dict[str, Any],
    self_consistency: float | None,
) -> str:
    lines: list[str] = []
    add = lines.append

    add("# Evaluation report")
    add("")
    add("Generated by `python eval/run_eval.py`. The narrative analysis lives in")
    add("[ERROR_ANALYSIS.md](./ERROR_ANALYSIS.md) and is written by hand.")
    add("")
    add("## Run configuration")
    add("")
    add("| Key | Value |")
    add("| --- | --- |")
    for key, value in run_metadata.items():
        add(f"| {key} | `{value}` |")
    add("")

    add("## Headline metrics")
    add("")
    add(f"Labelled subset: **n = {category_score.total}** of 30 tickets.")
    add("")
    add("| Metric | Value | 95% CI (Wilson) |")
    add("| --- | --- | --- |")
    add(_row("category_accuracy (exact)", category_score))
    add(_row("priority_agreement (exact)", priority_score))
    add(_row("priority within one level", priority_within_one))
    add("")
    add(
        "> One ticket moves any of these by "
        f"{100 / max(category_score.total, 1):.1f} points. Read the interval, not "
        "the point estimate."
    )
    add("")

    add("## Baselines and chance correction")
    add("")
    add("| Comparison | Value |")
    add("| --- | --- |")
    add(f"| Majority-class baseline (category) | {majority} |")
    add(f"| Heuristic-fallback baseline (category) | {heuristic_score} |")
    add(f"| LLM pipeline (category) | {category_score} |")
    add(f"| Cohen's kappa (category) | {cohens_kappa(category_pairs, CATEGORY_LABELS):.3f} |")
    add(f"| Cohen's kappa (priority) | {cohens_kappa(priority_pairs, PRIORITY_LABELS):.3f} |")
    add(f"| Macro F1 (category) | {macro_f1(category_pairs, CATEGORY_LABELS):.3f} |")
    add("")
    add("> The heuristic baseline is the number that matters. If the LLM does not")
    add("> clearly beat regex, it is not earning its latency.")
    add("")

    add("## Confusion matrix - category")
    add("")
    add(_matrix(confusion_matrix(category_pairs, CATEGORY_LABELS), CATEGORY_LABELS))
    add("")
    add("Rows are ground truth, columns are predictions.")
    add("")

    add("## Per-class performance - category")
    add("")
    add("| Class | Support | Precision | Recall | F1 |")
    add("| --- | --- | --- | --- | --- |")
    for metric in per_class_metrics(category_pairs, CATEGORY_LABELS):
        add(
            f"| {metric.label} | {metric.support} | {metric.precision:.2f} "
            f"| {metric.recall:.2f} | {metric.f1:.2f} |"
        )
    add("")

    add("## Confusion matrix - priority")
    add("")
    add(_matrix(confusion_matrix(priority_pairs, PRIORITY_LABELS), PRIORITY_LABELS))
    add("")

    add("## Confidence calibration")
    add("")
    add("Does confidence separate right answers from wrong ones? If the calibrated")
    add("separation is not better than the raw one, the calibration in PRD 7.2 did")
    add("not work, and this table says so.")
    add("")
    add("| Confidence | Mean when correct | Mean when incorrect | Separation |")
    add("| --- | --- | --- | --- |")
    add(_calibration_row("raw (model self-report)", calibration_raw))
    add(_calibration_row("calibrated (shipped)", calibration_calibrated))
    add("")

    if self_consistency is not None:
        add("## Determinism")
        add("")
        add(
            f"Two runs at temperature 0 with a fixed seed agreed on "
            f"**{self_consistency:.1%}** of the 30 tickets."
        )
        if self_consistency < 1.0:
            add("")
            add("Below 1.0. Local models are less deterministic than the parameters")
            add("suggest; reporting a single run as though it were stable would be a")
            add("subtle form of dishonesty.")
        add("")

    add("## Pipeline health (all 30 tickets)")
    add("")
    add("| Metric | Value |")
    add("| --- | --- |")
    for key, value in health.items():
        add(f"| {key} | `{value}` |")
    add("")

    add("## Disagreements with the ground truth")
    add("")
    if not disagreements:
        add("None on the labelled subset.")
    else:
        add("| Ticket | Field | Gold | Predicted | Conf | Stage | Subject |")
        add("| --- | --- | --- | --- | --- | --- | --- |")
        for row in disagreements:
            add(
                f"| {row['id']} | {row['field']} | `{row['gold']}` | "
                f"`{row['predicted']}` | {row['confidence']:.2f} | "
                f"{row['stage']} | {_escape(row['subject'])} |"
            )
    add("")
    return "\n".join(lines)


def _row(name: str, score: Score) -> str:
    low, high = score.interval
    return (
        f"| {name} | **{score.rate:.1%}** ({score.correct}/{score.total}) "
        f"| {low:.1%} - {high:.1%} |"
    )


def _calibration_row(name: str, report: CalibrationReport) -> str:
    return (
        f"| {name} | {report.mean_confidence_correct:.3f} "
        f"({report.n_correct}) | {report.mean_confidence_incorrect:.3f} "
        f"({report.n_incorrect}) | {report.separation:+.3f} |"
    )


def _matrix(matrix: dict[str, dict[str, int]], labels: list[str]) -> str:
    header = "| gold \\ pred | " + " | ".join(labels) + " |"
    divider = "| --- " * (len(labels) + 1) + "|"
    rows = [
        "| **" + gold + "** | " + " | ".join(str(matrix[gold][p]) for p in labels) + " |"
        for gold in labels
    ]
    return "\n".join([header, divider, *rows])


def _escape(text: str) -> str:
    return text.replace("|", "\\|").strip()[:60] or "(no subject)"
